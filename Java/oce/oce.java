package Java.oce;

public class oce {
    public static void main(String[] args) {
       int grade=75;
       if(grade>=90){
           System.out.println("优");
       } else if(grade>=80){
           System.out.println("良");
       } else if(grade>=70){
           System.out.println("中");
       } else if(grade>=60){
           System.out.println("及格");
       }
         else{
              System.out.println("不及格");
         }

    }
}
